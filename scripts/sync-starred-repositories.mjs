import { mkdir, writeFile } from "node:fs/promises";

const username = process.env.GITHUB_USERNAME ?? "ArkaPrabhaChowdhury";
const token = process.env.GITHUB_TOKEN;
const apiBase = "https://api.github.com";
const headers = {
  Accept: "application/vnd.github+json",
  "X-GitHub-Api-Version": "2022-11-28",
  ...(token ? { Authorization: `Bearer ${token}` } : {}),
};

async function getJson(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(`GitHub API ${response.status} for ${url}: ${await response.text()}`);
  }
  return response.json();
}

async function getStarredRepositories() {
  const endpoint = token ? `${apiBase}/user/starred` : `${apiBase}/users/${username}/starred`;
  const repositories = [];

  for (let page = 1; ; page += 1) {
    const pageItems = await getJson(`${endpoint}?per_page=100&page=${page}`);
    repositories.push(...pageItems);
    if (pageItems.length < 100) return repositories;
  }
}

function titleCase(value) {
  return value.replace(/[-_]+/g, " ").replace(/\b\w/g, (character) => character.toUpperCase());
}

function normalizeSkill(value) {
  const aliases = {
    js: "JavaScript",
    ts: "TypeScript",
    html: "HTML",
    css: "CSS",
    nextjs: "Next.js",
    reactjs: "React",
    nodejs: "Node.js",
    tailwindcss: "Tailwind CSS",
    postgresql: "PostgreSQL",
    postgres: "PostgreSQL",
    mongodb: "MongoDB",
    golang: "Go",
  };
  return aliases[value.toLowerCase()] ?? titleCase(value);
}

function unique(values) {
  return [...new Map(values.filter(Boolean).map((value) => [value.toLowerCase(), value])).values()];
}

function buildProject(repository, languages) {
  const languageSkills = Object.entries(languages)
    .sort(([, first], [, second]) => second - first)
    .map(([language]) => normalizeSkill(language));
  const topicSkills = (repository.topics ?? []).map(normalizeSkill);
  const skills = unique([...languageSkills, ...topicSkills]);
  const displayName = titleCase(repository.name);
  const description = repository.description?.trim() || "A project built and maintained on GitHub.";

  return {
    name: repository.full_name,
    displayName,
    stack: skills.join(", ") || "GitHub project",
    displayStack: skills.join(" · ") || "GitHub project",
    link: repository.html_url,
    linkLabel: repository.full_name,
    blurb: description,
    outcome: description,
    displayOutcome: description,
    challenge: description,
    bullets: [
      `Starred on GitHub${repository.language ? ` · Primary language: ${repository.language}` : ""}.`,
      ...(repository.topics?.length ? [`Topics: ${repository.topics.join(", ")}.`] : []),
    ],
    skills,
  };
}

const repositories = await getStarredRepositories();
const projects = await Promise.all(
  repositories.map(async (repository) => buildProject(repository, await getJson(repository.languages_url))),
);
const skills = unique(projects.flatMap((project) => project.skills)).sort((first, second) => first.localeCompare(second));

await mkdir("src/app", { recursive: true });
await writeFile(
  "src/app/generated-projects.ts",
  `// This file is generated by scripts/sync-starred-repositories.mjs.\n// Do not edit manually.\n\nexport type GeneratedProject = {\n  name: string;\n  displayName: string;\n  stack: string;\n  displayStack: string;\n  link: string;\n  linkLabel: string;\n  blurb: string;\n  outcome: string;\n  displayOutcome: string;\n  challenge: string;\n  bullets: string[];\n  skills: string[];\n};\n\nexport const generatedProjects: GeneratedProject[] = ${JSON.stringify(projects, null, 2)};\n\nexport const starredSkills: string[] = ${JSON.stringify(skills, null, 2)};\n`,
);

console.log(`Synced ${projects.length} starred repositories and ${skills.length} skills.`);
